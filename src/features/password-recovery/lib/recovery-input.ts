import {
  VILLAGE_CODE_REGEX,
  normalizeIdentifier,
  normalizeLoginVillageCode,
  type NormalizedIdentifier,
} from "../../../lib/auth/validators";

/*
 * Parsing of untrusted form input for password recovery. Everything here is
 * pure (no database, no session) and returns plain results, so the actions
 * decide what to do with a bad value.
 *
 * Reuses the sign-in parsing on purpose: an account is found the same way in
 * both places, so recovery can never match an account that sign-in could not.
 */

export interface RecoveryRequestInput {
  /** null means a System Admin account (blank village code), like sign-in. */
  villageCode: string | null;
  identifier: NormalizedIdentifier;
}

export type RecoveryRequestParse =
  | { ok: true; data: RecoveryRequestInput }
  | { ok: false };

/**
 * The public request form. A failure carries no detail: the caller still
 * answers with the one generic sentence, so a typo and an unknown account look
 * the same from outside.
 */
export function parseRecoveryRequestInput(input: {
  villageCode?: unknown;
  identifier?: unknown;
}): RecoveryRequestParse {
  const rawIdentifier =
    typeof input.identifier === "string" ? input.identifier : "";

  // Only a missing or blank text value means "System Admin account". Any
  // other type (a number, an uploaded file) is malformed and must not quietly
  // turn into an administrator lookup.
  if (
    input.villageCode !== undefined &&
    input.villageCode !== null &&
    typeof input.villageCode !== "string"
  ) {
    return { ok: false };
  }

  const rawVillageCode = input.villageCode ?? "";

  const identifier = normalizeIdentifier(rawIdentifier);

  if (!identifier) {
    return { ok: false };
  }

  let villageCode: string | null = null;

  if (rawVillageCode.trim()) {
    villageCode = normalizeLoginVillageCode(rawVillageCode);

    if (!VILLAGE_CODE_REGEX.test(villageCode)) {
      return { ok: false };
    }
  }

  return { ok: true, data: { villageCode, identifier } };
}

// Ids are generated by Prisma (cuid) and by tests (prefix + uuid): letters,
// digits, "-" and "_" only. Anything else cannot match a row, so it is refused
// before it reaches the database.
const REQUEST_ID_REGEX = /^[A-Za-z0-9_-]{1,64}$/;

/**
 * The request id an authority action works on. It is the ONLY identifying
 * input those actions accept (never a user id), which is what stops a Chief
 * from starting a reset for a member who has no request.
 */
export function parseRecoveryRequestId(raw: unknown): string | null {
  return typeof raw === "string" && REQUEST_ID_REGEX.test(raw) ? raw : null;
}
